#!/usr/bin/env python3
"""Combine the tool scores of every system repo into one scoreboard document.

Usage: python3 tools/combine_scores.py [--check] [--root <folder holding the system repos>]
Writes docs/TOOLS-SCOREBOARD.md. With --check it only compares and exits 1 when the file is stale.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import system_names  # noqa: E402

HUB = Path(__file__).resolve().parent.parent
OUT = HUB / "docs" / "TOOLS-SCOREBOARD.md"


def weighted(tool: dict, weights: dict) -> float:
    total = sum(weights.values())
    return round(sum(weights[k] * tool["scores"][k]["score"] for k in weights) / total, 1)


def load(root: Path) -> list[tuple[str, str, dict]]:
    out = []
    for name, repo in system_names.resolve(root):
        path = root / repo / "data" / "tool_scores.json"
        if not path.exists():
            raise SystemExit(f"missing {path}")
        out.append((name, repo, json.loads(path.read_text(encoding="utf-8"))))
    return out


def render(data: list[tuple[str, str, dict]]) -> str:
    lines = [
        "# Tools and alternatives, all seven systems together",
        "",
        "Generated by `tools/combine_scores.py` from the `data/tool_scores.json` of each system repo. Do not edit by hand.",
        "",
        "These are judgements from vendor documents and our own adapter work, dated per system. They are not benchmarks. A tool marked not run was never used against the real vendor. How the scores are made: `COMPARISON-METHOD.md`.",
        "",
    ]
    tools_total = groups_total = 0
    for name, repo, d in data:
        weights = d["weights"]
        lines += [f"## {name}", "", f"Scores dated {d['dated']}. Repo folder name while unpublished: `{repo}`.", ""]
        lines += ["| Job | Tool | Kind | Score | Closeness to the paid reference |", "| --- | --- | --- | --- | --- |"]
        for g in d["groups"]:
            groups_total += 1
            by_id = {t["id"]: t for t in g["tools"]}
            ref = by_id.get(g["reference"])
            for t in sorted(g["tools"], key=lambda x: -weighted(x, weights)):
                tools_total += 1
                close = ""
                if ref and t["kind"] != "paid" and ref["scores"]["fit"]["score"]:
                    close = f"{round(100 * t['scores']['fit']['score'] / ref['scores']['fit']['score'])} percent"
                elif t["id"] == g["reference"]:
                    close = "reference"
                lines.append(f"| {g['job']} | {t['name']} | {t['kind']} | {weighted(t, weights)} | {close} |")
        lines += [""]
    lines += ["## Totals", "", f"{groups_total} comparison groups and {tools_total} scored tools across seven systems.", ""]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(HUB.parent))
    a = ap.parse_args()
    text = render(load(Path(a.root)))
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("OK scoreboard is current" if ok else "STALE: run tools/combine_scores.py")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
