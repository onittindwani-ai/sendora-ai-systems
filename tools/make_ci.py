#!/usr/bin/env python3
"""Write the same GitHub Actions workflow into a system repo.

Usage: python3 tools/make_ci.py <repo folder> [--check]

One template for all seven systems, so the CI of every repo proves the same things:
  python  tests with coverage, then the repo's own checks (seed score, tool score, docs, secrets)
  web     typecheck, production build, browser tests against the real API on a clean runner
  docker  the compose stack is built and started, and the API and the web app answer
  audit   known vulnerabilities in the Python and Node dependencies that ship

Every third party action is pinned to a commit. The workflow can read the code and nothing else.
`--check` exits 1 when the repo's workflow differs from what this tool would write.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

# commit pins of the actions used (looked up on GitHub on 2026-11-25; the tag is the comment)
CHECKOUT = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1  # v7.0.1"
SETUP_PYTHON = "actions/setup-python@6d4fd22b20465ccc0f7354476588e8df7c9ca0e0  # v7.1.0"
SETUP_NODE = "actions/setup-node@949feb2413d6458794dcd2491c4babbbce0c15c1  # v7.1.0"
PNPM = "pnpm/action-setup@73e46992e05b19abd31f2f3c20e0e7370d762115  # v6.1.1"
UPLOAD = "actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9  # v7.0.2"

TEMPLATE = """# Generated by tools/make_ci.py in the hub repository (sendora-ai-systems). Edit the template there, not this file.
name: ci
on:
  push:
  pull_request:
permissions:
  contents: read
concurrency:
  group: ci-${{ github.workflow }}-${{ github.ref }}
  cancel-in-progress: true
env:
  PYTHONDONTWRITEBYTECODE: "1"
jobs:
  python:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: __CHECKOUT__
      - uses: __SETUP_PYTHON__
        with:
          python-version: "3.12"
          cache: pip
          cache-dependency-path: |
            constraints.txt
            packages/core-py/pyproject.toml
            apps/api/pyproject.toml
      - run: pip install -c constraints.txt -e packages/core-py -e "apps/api[dev]"
      - run: python -m pytest -q
__PYTHON_CHECKS__
  web:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: __CHECKOUT__
      - uses: __PNPM__
      - uses: __SETUP_NODE__
        with:
          node-version: 22
          cache: pnpm
      - uses: __SETUP_PYTHON__
        with:
          python-version: "3.12"
          cache: pip
          cache-dependency-path: |
            constraints.txt
            packages/core-py/pyproject.toml
            apps/api/pyproject.toml
      # the browser tests start the API from .venv, the same place `make install` puts it
      - run: python -m venv .venv && .venv/bin/pip install -c constraints.txt -e packages/core-py -e "apps/api[dev]"
      - run: pnpm install --frozen-lockfile
      - run: pnpm typecheck
      - run: pnpm test:ui
      - run: pnpm build
      - run: pnpm exec playwright install --with-deps chrome
        working-directory: apps/web
      - run: pnpm e2e
      - if: failure()
        uses: __UPLOAD__
        with:
          name: playwright-report
          path: |
            apps/web/test-results
            apps/web/playwright-report
          if-no-files-found: ignore
          retention-days: 7
  docker:
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: __CHECKOUT__
      - name: Write a throwaway .env
        run: |
          cp .env.example .env
          {
            echo "POSTGRES_PASSWORD=$(openssl rand -hex 16)"
            echo "SESSION_SECRET=$(openssl rand -hex 32)"
            echo "WEBHOOK_SHARED_SECRET=$(openssl rand -hex 16)"
            echo "ALLOW_DEMO_SERVER=true"  # a throw away demo on Postgres, which the app refuses otherwise
          } >> .env
      - run: docker compose build
      - name: Start the stack
        run: |
          docker compose up -d || { docker compose ps -a; docker compose logs --tail 120 api worker web; exit 1; }
      - name: The API and the web app answer
        run: |
          for i in $(seq 1 60); do
            if curl -fsS http://127.0.0.1:8000/health >/dev/null && curl -fsS http://127.0.0.1:3000/login >/dev/null; then echo "up after ${i} tries"; exit 0; fi
            sleep 3
          done
          docker compose ps
          docker compose logs --tail 80
          exit 1
      - if: always()
        run: docker compose down -v
  audit:
    runs-on: ubuntu-latest
    timeout-minutes: 15
    steps:
      - uses: __CHECKOUT__
      - uses: __SETUP_PYTHON__
        with:
          python-version: "3.12"
      - run: pip install pip-audit && pip install -c constraints.txt -e packages/core-py -e apps/api && pip-audit --skip-editable
      - uses: __PNPM__
      - uses: __SETUP_NODE__
        with:
          node-version: 22
          cache: pnpm
      - run: pnpm install --frozen-lockfile && pnpm audit --prod --audit-level=high
"""

CHECKS = (
    ("score_seed.py", "python tools/score_seed.py"),
    ("score_tools.py", "python tools/score_tools.py --check"),
    ("check_docs.py", "python tools/check_docs.py"),
    ("scan_secrets.py", "python tools/scan_secrets.py"),
)


def render(repo: Path) -> str:
    lines = [f"      - run: {cmd}" for tool, cmd in CHECKS if (repo / "tools" / tool).is_file()]
    text = TEMPLATE.replace("__PYTHON_CHECKS__", "\n".join(lines))
    for key, value in (("CHECKOUT", CHECKOUT), ("SETUP_PYTHON", SETUP_PYTHON), ("SETUP_NODE", SETUP_NODE), ("PNPM", PNPM), ("UPLOAD", UPLOAD)):
        text = text.replace(f"__{key}__", value)
    return text


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("repo", type=Path)
    ap.add_argument("--check", action="store_true", help="exit 1 when the workflow differs, write nothing")
    args = ap.parse_args(argv)
    repo = args.repo.resolve()
    if not (repo / "apps" / "api").is_dir():
        print(f"Not a system repo: {repo}", file=sys.stderr)
        return 2
    target = repo / ".github" / "workflows" / "ci.yml"
    wanted = render(repo)
    if args.check:
        same = target.is_file() and target.read_text() == wanted
        print("ci.yml matches the template" if same else "ci.yml differs from the template")
        return 0 if same else 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(wanted)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
